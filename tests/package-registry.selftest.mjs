import assert from "node:assert/strict";
import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { FirstPartyPackageRegistry, FIRST_PARTY_PACKAGES, validatePackageManifest } from "../core/runtime/index.mjs";

const base = { type: "skill", id: "local-seo", version: "1.0.0", publisher: "GhostCursor", firstParty: true, capabilities: ["seo.audit"], content: "Use verified facts only." };
assert.equal(validatePackageManifest(base).valid, true);
assert.equal(validatePackageManifest({ ...base, executable: true }).valid, false);
assert.equal(validatePackageManifest({ ...base, publisher: "unknown" }).valid, false);
const registry = new FirstPartyPackageRegistry();
const skill = registry.publish(base);
assert.ok(skill.digest);
const reordered = new FirstPartyPackageRegistry().publish({ content: base.content, capabilities: base.capabilities, firstParty: true, publisher: "GhostCursor", version: "1.0.0", id: "local-seo", type: "skill" });
assert.equal(reordered.digest, skill.digest, "manifest field order does not change package identity");
const agent = registry.publish({ type: "agent", id: "seo-growth", version: "1.0.0", publisher: "GhostCursor", firstParty: true, capabilities: ["seo.audit"], skills: ["local-seo"] });
assert.equal(registry.list({ type: "agent" })[0].id, agent.id);
const disabled = registry.setStatus("skill", "local-seo", "1.0.0", "disabled");
assert.equal(disabled.history.at(-1).to, "disabled");
assert.equal(disabled.history.at(-1).from, "published");
assert.equal(registry.list().some((item) => item.id === "local-seo"), false);
const stateFile = join(await mkdtemp(join(tmpdir(), "businessos-package-registry-")), "packages.json");
const persisted = new FirstPartyPackageRegistry({ stateFile });
persisted.publish(base); await persisted.save();
const reloaded = new FirstPartyPackageRegistry({ stateFile }); await reloaded.load();
assert.equal(reloaded.list()[0].id, "local-seo");
const tampered = JSON.parse(await readFile(stateFile, "utf8")); tampered[0].capabilities.push("system.shell"); await writeFile(stateFile, JSON.stringify(tampered));
await assert.rejects(() => new FirstPartyPackageRegistry({ stateFile }).load(), /integrity check failed/);
console.log("first-party package registry self-test passed");
assert.equal(FIRST_PARTY_PACKAGES.length, 8);
assert.ok(FIRST_PARTY_PACKAGES.every((manifest) => validatePackageManifest(manifest).valid));
